import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const {WorldStreamer} = await import('../web/world/streamer.js');
const settings = JSON.parse(readFileSync(new URL('../config/world.json', import.meta.url)));
delete settings.distant_terrain_level; // Isolate the user-controlled detailed radius.
const streamer = new WorldStreamer({}, settings);
streamer.pump = () => {};
const destroyed = [];
const entry = (name, age) => ({last_used_ms:age, tile:{memory_bytes:1024*1024, setVisible(){}, destroy:()=>destroyed.push(name)}});
streamer.settings = {...settings, retain_loaded_tiles:true, tile_memory_limit_mb:3};
streamer.desired = new Set(['active']);
streamer.resident.set('recent', entry('recent', 2));
streamer.resident.set('old', entry('old', 1));
streamer.resident.set('active', entry('active', 0));
streamer.trim();
assert.equal(streamer.resident.size, 3, 'retains old tiles while within budget');
streamer.settings.tile_memory_limit_mb = 2;
streamer.trim();
assert.deepEqual(destroyed, ['old'], 'oldest inactive tile goes first');
streamer.settings.tile_memory_limit_mb = .5;
streamer.trim();
assert.deepEqual([...streamer.resident.keys()], ['active'], 'active area remains even below minimum budget');
streamer.resident.set('recent', entry('recent', 2));
streamer.settings.retain_loaded_tiles = false;
streamer.trim();
assert.deepEqual([...streamer.resident.keys()], ['active'], 'disabling retention immediately removes inactive tiles');
streamer.configure({retain_loaded_tiles:true, tile_memory_limit_mb:32, active_radius_tiles:2});
streamer.update({longitude_deg:34.38, latitude_deg:49.57});
assert.equal(streamer.desired.size, 25, 'radius is not truncated by old nine-tile cap');
streamer.configure({retain_loaded_tiles:true, tile_memory_limit_mb:32, active_radius_tiles:0});
assert.equal(streamer.desired.size, 1, 'radius zero keeps only current tile');
console.log('PASS retention, LRU, budget reduction, active area and radius changes');
