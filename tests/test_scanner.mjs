import assert from 'node:assert/strict';
import {scannerContact, scaleContact, scannerGround} from '../web/scanner-math.mjs';
const pose = {latitude_deg:0,longitude_deg:0,altitude_asl_m:100,yaw_deg:0,pitch_deg:0,roll_deg:0};
const north = {latitude_deg:.001,longitude_deg:0,altitude_relative_m:100};
const east = {latitude_deg:0,longitude_deg:.001,altitude_relative_m:100};
let contact = scannerContact(pose,north,0);
assert.ok(contact.forward_m > 111 && Math.abs(contact.right_m)<1e-6);
contact = scannerContact({...pose,yaw_deg:90},east,0);
assert.ok(contact.forward_m > 111 && Math.abs(contact.right_m)<1e-6);
contact = scannerContact({...pose,yaw_deg:90},north,0);
assert.ok(contact.right_m < -111, 'north is left when heading east');
contact = scannerContact(pose,{...north,latitude_deg:0,altitude_relative_m:150},0);
assert.ok(Math.abs(contact.up_m-50)<1e-6);
assert.equal(contact.height_difference_m,50);
contact = scannerContact({...pose,pitch_deg:30},north,0);
assert.ok(contact.up_m < -55, 'level target lies below raised nose plane');
contact = scannerContact({...pose,roll_deg:30},east,0);
assert.ok(contact.up_m > 55, 'right bank places east above the lowered right wing plane');
const scaled = scaleContact({right_m:300,forward_m:400,up_m:0,distance_m:500},100);
assert.ok(scaled.outside);
assert.equal(Math.hypot(scaled.x,scaled.y,scaled.z),1);
assert.equal(scaleContact({right_m:0,forward_m:0,up_m:0,distance_m:0},200).z,0);
console.log('PASS scanner heading, altitude, pitch, roll, range boundary and coincident position');
const ground = scannerGround({...pose,altitude_agl_m:100},500);
assert.deepEqual(ground.foot,[0,0,-.2]);
assert.ok(ground.rim.every(p=>Math.abs(Math.hypot(...p)-1)<1e-10));
assert.ok(scannerGround({...pose,altitude_agl_m:100,roll_deg:90},500).foot[0]>.19);
assert.equal(scannerGround({...pose,altitude_agl_m:1000},500).outside,true);
assert.equal(scannerGround(pose,500),null);
console.log('PASS ground altitude, sphere intersection, banking and missing telemetry');
